#!/usr/bin/env bash


################################################################################
## Environment
################################################################################

set -e						# exit on error
set -o pipefail				# exit on pipeline error
set -u						# treat unset variable as error


################################################################################
## Base Path
################################################################################

BASE_DIR_PATH="$(dirname "$(realpath "${0}")")"


################################################################################
## Init
################################################################################




################################################################################
## Option
################################################################################




################################################################################
## Module
################################################################################

function mod_pipx_install () {

	local run_cmd="apt-get install -y --install-recommends
		pipx
	"

	echo ${run_cmd}
	${run_cmd}

}

function mod_gext_install () {

	local run_cmd="pipx install gnome-extensions-cli --global"

	echo ${run_cmd}
	${run_cmd}

}




################################################################################
## Model
################################################################################

function model_desktop_environment_gnome_shell_extensions_cli () {

	mod_pipx_install
	mod_gext_install

}




################################################################################
## Portal
################################################################################

function portal_desktop_environment_gnome_shell_extensions_cli () {

	model_desktop_environment_gnome_shell_extensions_cli

}


################################################################################
## Main
################################################################################

echo "################################################################################"
echo "## [Hook] run: ${0} "
echo "################################################################################"

echo "==== args:" ${@} "===="

function __main__ () {

	portal_desktop_environment_gnome_shell_extensions_cli "${@}"

}

__main__ "${@}"


